-- ============================================================
-- 首页推荐商品功能字段（2026-10-08）
-- 背景：FR-01-04 要求"按后台管理设置推荐当季农特产"，
--       此前首页推荐为后端写死按销量取前 10。
-- 本次：商品表加"推荐"标记列，平台管理端商品列表以开关勾选，
--       首页改为展示已勾选推荐中的上架商品（按销量排，前 10）；
--       一个都没勾选时回退销量前 10，保证首页不为空。
--
-- 在现有库上执行一次即可（导入 db/schema.sql 的全新库已含此列，无需再执行）。
-- ============================================================

ALTER TABLE `product`
  ADD COLUMN `is_recommend` TINYINT NOT NULL DEFAULT 0 COMMENT '是否首页推荐：0否 1是（平台管理端勾选）' AFTER `audit_pass`;

-- 可选：把当前销量前 10 的上架商品直接置为推荐，首页展示不变、无缝切换
-- （不需要保持现状的话，注释掉这句即可，后台没勾时首页自动回退销量前 10）
UPDATE `product` SET `is_recommend` = 1
WHERE `status` = 1
ORDER BY `sales` DESC
LIMIT 10;
